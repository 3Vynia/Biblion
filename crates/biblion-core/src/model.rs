use serde::{Deserialize, Serialize};

pub type BookId = i64;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Format {
    Epub,
    Pdf,
    Cbz,
    Cbr,
    Mobi,
    Azw3,
}

impl Format {
    pub const ALL: [Format; 6] =
        [Format::Epub, Format::Pdf, Format::Cbz, Format::Cbr, Format::Mobi, Format::Azw3];

    pub fn from_extension(ext: &str) -> Option<Self> {
        Some(match ext.to_ascii_lowercase().as_str() {
            "epub" => Format::Epub,
            "pdf" => Format::Pdf,
            "cbz" => Format::Cbz,
            "cbr" => Format::Cbr,
            "mobi" | "prc" => Format::Mobi,
            "azw3" | "azw" | "kf8" => Format::Azw3,
            _ => return None,
        })
    }

    pub fn from_path(path: &std::path::Path) -> Option<Self> {
        path.extension().and_then(|e| e.to_str()).and_then(Self::from_extension)
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Format::Epub => "epub",
            Format::Pdf => "pdf",
            Format::Cbz => "cbz",
            Format::Cbr => "cbr",
            Format::Mobi => "mobi",
            Format::Azw3 => "azw3",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        Self::from_extension(s)
    }

    pub fn is_comic(self) -> bool {
        matches!(self, Format::Cbz | Format::Cbr)
    }
}

/// Someone who worked on a book other than its authors.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Contributor {
    pub name: String,
    /// MARC relator code: `trl` translator, `ill` illustrator, `edt` editor,
    /// `nrt` narrator, `ctb` contributor (when unknown)…
    pub role: String,
}

/// A book identifier with its scheme (`isbn`, `uuid`, `asin`, `doi`…).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Identifier {
    pub scheme: String,
    pub value: String,
}

/// Metadata extracted from a file (before it is stored in the DB).
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct Metadata {
    pub title: Option<String>,
    pub authors: Vec<String>,
    pub series: Option<String>,
    pub series_index: Option<f64>,
    pub publisher: Option<String>,
    pub language: Option<String>,
    pub isbn: Option<String>,
    pub published: Option<String>,
    pub description: Option<String>,
    pub tags: Vec<String>,
    pub page_count: Option<u32>,
    pub subtitle: Option<String>,
    pub contributors: Vec<Contributor>,
    pub identifiers: Vec<Identifier>,
    pub rights: Option<String>,
    pub source: Option<String>,
    /// Last modification of the edition, as written in the file.
    pub modified: Option<String>,
    /// e.g. "EPUB 3.0", "PDF 1.7", "MOBI 6".
    pub format_version: Option<String>,
}

/// Numbers generated by analysing a book's content (see `Library::analyze`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BookStats {
    pub words: u64,
    /// Non-whitespace characters of the text.
    pub characters: u64,
    /// Entries in the table of contents (or sections when there is none).
    pub chapters: u32,
    pub images: u32,
    /// Estimate at 250 words per minute.
    pub reading_minutes: u32,
}

impl BookStats {
    pub const WORDS_PER_MINUTE: u64 = 250;

    pub fn new(words: u64, characters: u64, chapters: u32, images: u32) -> Self {
        let reading_minutes = words.div_ceil(Self::WORDS_PER_MINUTE) as u32;
        Self { words, characters, chapters, images, reading_minutes }
    }
}

/// What an annotation marks: a passage (with optional note) or a page.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum AnnotationKind {
    Highlight,
    Bookmark,
}

impl AnnotationKind {
    pub fn as_str(self) -> &'static str {
        match self {
            AnnotationKind::Highlight => "highlight",
            AnnotationKind::Bookmark => "bookmark",
        }
    }
}

/// A highlight (quote, with an optional note) or a bookmark in a book.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Annotation {
    pub id: i64,
    pub book_id: BookId,
    pub kind: AnnotationKind,
    /// Opaque position for the reader (an EPUB CFI or CFI range).
    pub locator: String,
    /// The highlighted passage, or the first words of a bookmarked page.
    pub text: String,
    pub note: Option<String>,
    pub color: Option<String>,
    pub chapter: Option<String>,
    /// Position in the book, 0.0 – 1.0 (orders annotations in reading order).
    pub percent: f64,
    pub created_at: i64,
    pub updated_at: i64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NewAnnotation {
    pub book_id: BookId,
    pub kind: AnnotationKind,
    pub locator: String,
    pub text: String,
    pub note: Option<String>,
    pub color: Option<String>,
    pub chapter: Option<String>,
    pub percent: f64,
}

